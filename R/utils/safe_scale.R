
#' Safe scaling for time series and other complex objects
#'
#' @param x An object to be scaled (e.g., numeric matrix, ts, xts, zoo)
#' @param center logical or numeric vector
#' @param scale logical or numeric vector
#' @return A scaled version of x preserving class and attributes
safe_scale <- function(x, center = TRUE, scale = TRUE) {
  # If it's a data.frame or tibble, base::scale() handles it fine (converts to matrix).
  # We should NOT try to preserve data.frame attributes on a matrix.
  if (inherits(x, "data.frame")) {
    return(base::scale(x, center = center, scale = scale))
  }

  # Preserve original class and attributes
  orig_attrs <- attributes(x)

  # Ensure we extract data properly without flattening matrices
  if (inherits(x, c("ts", "xts", "zoo"))) {
    if (requireNamespace("zoo", quietly = TRUE)) {
      core_x <- zoo::coredata(x)
    } else {
      # Use as.matrix to preserve columns, as.numeric flattens
      core_x <- as.matrix(x)
    }
  } else {
    core_x <- x
  }

  # Perform standard scaling
  res <- base::scale(core_x, center = center, scale = scale)

  # Capture scaling attributes generated by scale()
  scale_center <- attr(res, "scaled:center")
  scale_scale <- attr(res, "scaled:scale")

  # Restore original attributes if they existed
  if (!is.null(orig_attrs)) {
    attributes(res) <- orig_attrs
  }

  # Re-attach the specific scaling attributes
  attr(res, "scaled:center") <- scale_center
  attr(res, "scaled:scale") <- scale_scale

  return(res)
}
